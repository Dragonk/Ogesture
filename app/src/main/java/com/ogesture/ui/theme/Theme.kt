/** Status colors that aren't part of the Material color scheme. */
@Immutable
data class ExtendedColors(
    val success: Color,
    val warning: Color,
)

private val LightExtendedColors = ExtendedColors(success = SuccessLight, warning = WarningLight)
private val DarkExtendedColors = ExtendedColors(success = SuccessDark, warning = WarningDark)

private val LocalExtendedColors = staticCompositionLocalOf { LightExtendedColors }

object ExtendedTheme {
    val colors: ExtendedColors
        @Composable get() = LocalExtendedColors.current
}

@Composable
fun OgestureTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Dynamic color is available on Android 12+
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }

        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }
    val extendedColors = if (darkTheme) DarkExtendedColors else LightExtendedColors

    CompositionLocalProvider(LocalExtendedColors provides extendedColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content
        )
    }
}
